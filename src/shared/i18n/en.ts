/**
 * The English message catalogue — the source of truth of the translation.
 *
 * Every user visible string of OpenNotes lives here. The other locales in
 * `./locales` only hold the keys they have translated; a key that is missing
 * falls back to the English text, so a half finished translation never breaks
 * the application.
 *
 * Rules for this file:
 *
 * 1. A key is a dotted path that names the place it belongs to
 *    (`panel.files`, `status.line`, `cmd.file.save`).
 * 2. The value is plain text. Placeholders are written as `{{name}}` and are
 *    replaced by `translate()`.
 * 3. The file is sorted by group so that a translator can work through it
 *    without touching the rest.
 */

