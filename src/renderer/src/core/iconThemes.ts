/**
 * Icon theme pack for OpenNotes.
 *
 * Every theme recolours the shared shape library in `iconShapes.ts` and may
 * override a few shapes of its own. The looks are inspired by well known
 * open source icon sets and editor colour schemes - the origin of each look
 * is recorded in the `basedOn` field.
 *
 * Colours are plain `#rrggbb` strings so the renderer can hand them straight
 * to `fill` (or to `currentColor` by using the empty string plus
 * `monochrome: true`).
 *
 * Usage in the renderer:
 *   const theme = iconTheme(settings.iconTheme)
 *   const kind = iconKindFor(entry.name, entry.isDir)
 *   const d = theme.shapes?.[kind] ?? ICON_SHAPES[kind]
 *   const fill = theme.colors[kind]
 * The `none` theme returns empty colours, which is the signal to hide the
 * icon altogether.
 */
import type { IconKind } from './iconShapes'

export interface IconThemeEntry {
  id: string
  label: string
  /** Where the look comes from, e.g. "Seti UI (Apache-2.0)". */
  basedOn: string
  /** Colour per kind. */
  colors: Record<IconKind, string>
  /** Optional shape overrides for this theme (kind -> path data). */
  shapes?: Partial<Record<IconKind, string>>
  /** When true the theme draws plain monochrome shapes. */
  monochrome?: boolean
}

/* ------------------------------------------------------------------ *
 * Palette helpers
 * ------------------------------------------------------------------ */

/** The colour groups a theme has to fill in. */
interface PaletteSpec {
  /** Folder / folder-open. */
  folder: string
  /** Generic files and plain text. */
  file: string
  /** Source code. */
  code: string
  /** Markup (markdown, html, css, xml). */
  markup: string
  /** Structured data (json, yaml, sql, csv). */
  data: string
  /** Media (image, video, audio, font). */
  media: string
  /** Documents (pdf, office). */
  doc: string
  /** Everything else (config, archives, binaries, lock, docker, git). */
  misc: string
  /** Optional per language overrides. */
  langs?: Partial<Record<IconKind, string>>
}

/**
 * Expand the colour groups into a complete `Record<IconKind, string>`.
 * Every kind is listed explicitly so the compiler catches omissions.
 */
function buildColors(spec: PaletteSpec): Record<IconKind, string> {
  const lang = spec.langs ?? {}
  return {
    folder: spec.folder,
    'folder-open': spec.folder,
    file: spec.file,
    code: spec.code,
    text: spec.file,
    markdown: spec.markup,
    'markdown-file': spec.markup,
    data: spec.data,
    config: spec.misc,
    image: spec.media,
    video: spec.media,
    audio: spec.media,
    font: spec.media,
    archive: spec.misc,
    binary: spec.misc,
    pdf: spec.doc,
    spreadsheet: spec.data,
    presentation: spec.doc,
    java: lang.java ?? spec.code,
    kotlin: lang.kotlin ?? spec.code,
    go: lang.go ?? spec.code,
    rust: lang.rust ?? spec.code,
    python: lang.python ?? spec.code,
    cpp: lang.cpp ?? spec.code,
    csharp: lang.csharp ?? spec.code,
    php: lang.php ?? spec.code,
    ruby: lang.ruby ?? spec.code,
    swift: lang.swift ?? spec.code,
    sql: lang.sql ?? spec.data,
    shell: lang.shell ?? spec.code,
    html: lang.html ?? spec.markup,
    css: lang.css ?? spec.markup,
    json: lang.json ?? spec.data,
    yaml: lang.yaml ?? spec.data,
    xml: lang.xml ?? spec.markup,
    lock: spec.misc,
    docker: lang.docker ?? spec.misc,
    git: lang.git ?? spec.misc,
  }
}

/** All kinds share one colour. */
function mono(color: string): Record<IconKind, string> {
  const out = {} as Record<IconKind, string>
  const kinds: IconKind[] = [
    'folder',
    'folder-open',
    'file',
    'code',
    'text',
    'markdown',
    'data',
    'config',
    'image',
    'video',
    'audio',
    'font',
    'archive',
    'binary',
    'pdf',
    'spreadsheet',
    'presentation',
    'java',
    'kotlin',
    'go',
    'rust',
    'python',
    'cpp',
    'csharp',
    'php',
    'ruby',
    'swift',
    'sql',
    'shell',
    'html',
    'css',
    'json',
    'yaml',
    'xml',
    'markdown-file',
    'lock',
    'docker',
    'git',
  ]
  for (const kind of kinds) out[kind] = color
  return out
}

