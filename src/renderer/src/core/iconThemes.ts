/** Look up a theme by id, falling back to the first theme. */
export function iconTheme(id: string): IconThemeEntry {
  return ICON_THEMES.find((theme) => theme.id === id) ?? ICON_THEMES[0]
}

/** All theme ids, in display order. */
export function iconThemeIds(): string[] {
  return ICON_THEMES.map((theme) => theme.id)
}
