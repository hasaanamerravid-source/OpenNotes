/** Look up one theme (undefined when unknown). */
export function themePackEntry(id: string): ThemePackEntry | undefined {
  return THEME_PACK.find((theme) => theme.id === id)
}

/** Themes grouped for the settings gallery. */
export function themePackGroups(): { group: string; themes: ThemePackEntry[] }[] {
  const order: ThemePackEntry['group'][] = ['Dark', 'Light', 'Contrast']
  const groups: { group: string; themes: ThemePackEntry[] }[] = []
  for (const group of order) {
    const themes = THEME_PACK.filter((theme) => theme.group === group)
    if (themes.length > 0) groups.push({ group, themes })
  }
  return groups
}
