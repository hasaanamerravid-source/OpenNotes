/**
 * Theme pack: a large collection of open source derived editor colour themes.
 *
 * Every palette in this file re-implements a well known community theme
 * (Material, Dracula, Nord, Gruvbox, Catppuccin, Solarized, ...).  The
 * originals are MIT licensed; the `basedOn` field records where a palette
 * comes from so the credits stay visible in the settings gallery.
 *
 * This file is pure data on purpose: no CodeMirror import lives here.  The
 * wiring in `syntaxThemes.ts` turns these palettes into a `HighlightStyle`.
 */

/** A single theme of the pack: editor chrome colours plus token colours. */
export interface ThemePackEntry {
  id: string
  label: string
  /** 'Dark' | 'Light' | 'Contrast' */
  group: 'Dark' | 'Light' | 'Contrast'
  dark: boolean
  /** Where the palette comes from (e.g. "Material (MIT)"). */
  basedOn: string
  editor: {
    background: string
    foreground: string
    caret: string
    selection: string
    activeLine: string
    gutterBackground: string
    gutterForeground: string
    activeGutterForeground: string
    matchingBracket: string
    searchMatch: string
    indentGuide: string
    comment: string
    lineNumber: string
  }
  tokens: {
    keyword: string
    string: string
    comment: string
    number: string
    function: string
    type: string
    tag: string
    property: string
    operator: string
    constant: string
    variable: string
    punctuation: string
    heading: string
    emphasis: string
    strong: string
    link: string
    invalid: string
  }
}

